/** Búsqueda por nombre (case/acento-insensitive). */
export function buscarMunicipio(query: string): MunicipioMichoacan | null {
  if (!query) return null;
  const norm = (s: string) =>
    s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();
  const q = norm(query);
  return (
    MUNICIPIOS_MICHOACAN_113.find((m) => norm(m.nombre) === q) ??
    MUNICIPIOS_MICHOACAN_113.find((m) => norm(m.nombre).includes(q)) ??
    null
  );
}
